"""T1.3 - charger comparison.

Reads calcs/data/chargers.csv (datasheet values only, blanks where a datasheet
is silent) and writes docs/04-charger-comparison.md.

For every DC charger it also derives the grid current from P = sqrt(3)*U*I*PF
and puts it next to the datasheet current, so a reviewer can see why the design
uses the datasheet figure (it covers low grid voltage and part-load losses).
"""
from __future__ import annotations

import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "calcs" / "data" / "chargers.csv"
OUT = ROOT / "docs" / "04-charger-comparison.md"

U_NOM = 400.0  # V line-to-line, A02


def load(path: Path = DATA) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(v: str) -> float | None:
    return float(v) if v not in ("", None) else None


def derived_input_current(p_out_kw: float, eff: float, pf: float, u: float = U_NOM) -> float:
    """Grid current per phase for a DC charger at full output, nominal voltage."""
    return p_out_kw * 1000 / (eff * math.sqrt(3) * u * pf)


def design_current(row: dict) -> tuple[float, str]:
    """Current used for cable sizing: datasheet value if given, else derived."""
    ds = num(row["input_current_a"])
    if ds is not None:
        return ds, "datasheet"
    eff = (num(row["efficiency_pct"]) or 95) / 100
    pf = num(row["pf"]) or 0.99
    return derived_input_current(float(row["rated_output_kw"]), eff, pf), "derived"


def cell(v: str, unit: str = "", prefix: str = "") -> str:
    return f"{prefix}{v}{unit}" if v else "not stated"


def table(rows: list[dict], role: str) -> str:
    head = ("| ID | Charger | Output | Connector | Input I (A) | PF | THDi | "
            "Efficiency | Standby | IP / IK | Ambient (°C) | OCPP |\n"
            "|---|---|---|---|---|---|---|---|---|---|---|---|\n")
    lines = []
    for r in (r for r in rows if r["role"] == role):
        i, basis = design_current(r)
        i_txt = f"{i:.0f}" + ("" if basis == "datasheet" else " (derived)")
        ipik = f"{r['ip'] or '?'} / {r['ik'] or '?'}"
        amb = f"{r['temp_min_c']} to {r['temp_max_c']}"
        if role == "AC":
            pf = thd = eff = "set by vehicle"
        else:
            pf = cell(r["pf"], prefix="≥ ")
            thd = cell(r["thdi_pct"], " %", "< ")
            eff = cell(r["efficiency_pct"], " % max")
        lines.append(
            f"| {r['id']} | {r['make']} {r['model']} | {r['output_split']} | "
            f"{r['connectors']} | {i_txt} | {pf} | {thd} | {eff} | "
            f"{cell(r['standby_w'], ' W')} | {ipik} | {amb} | {r['ocpp']} |"
        )
    return head + "\n".join(lines) + "\n"


def current_check(rows: list[dict]) -> str:
    out = ("| ID | Derived at 400 V, full load (A) | Datasheet (A) | Used for sizing (A) |\n"
           "|---|---|---|---|\n")
    for r in (r for r in rows if r["role"] == "DC"):
        d = derived_input_current(float(r["rated_output_kw"]),
                                  (num(r["efficiency_pct"]) or 95) / 100,
                                  num(r["pf"]) or 0.99)
        ds = r["input_current_a"] or "not stated"
        used, _ = design_current(r)
        out += f"| {r['id']} | {d:.1f} | {ds} | {used:.0f} |\n"
    return out


def render(rows: list[dict]) -> str:
    src = "\n".join(f"- {r['id']}: {r['make']} {r['model']}, {r['datasheet_ref']}. "
                    f"<{r['source_url']}>" for r in rows)
    return f"""# 04 · Charger comparison (T1.3)

Generated by `calcs/chargers.py` from `calcs/data/chargers.csv`. Do not edit by hand.
"not stated" means the datasheet read is silent on that value; it is not a zero.
The choice and reasons are in `docs/decisions/DEC-02-chargers.md`.

## AC candidates (22 kW, three-phase, 32 A)

{table(rows, "AC")}
An AC wallbox does no power conversion. Power factor, THD and conversion losses
come from the on-board charger in the car, which is why no AC datasheet lists them.

## DC candidates

{table(rows, "DC")}
## Grid current: derived vs datasheet

{current_check(rows)}
The datasheet current is higher than P / (√3 · U · PF · η) because it covers grid
voltage below 400 V and losses below peak efficiency. Cable sizing in T3.2 uses
the datasheet value whenever one exists.

## Sources

{src}
"""


def main() -> None:
    rows = load()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(rows), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} chargers)")


if __name__ == "__main__":
    main()
